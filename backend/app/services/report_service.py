"""Report export: JSON and PDF (spec §13; DOCX dropped by Amendment A1).

The PDF keeps source-derived claims and system-generated content apart: every item shows
its origin, verification status and page reference. Missing categories are reported as
missing, never filled in.
"""

from __future__ import annotations

import json
import re
import uuid
from pathlib import Path
from typing import Any, Literal

from app.config import Settings
from app.errors import AppError
from app.schemas.extraction import ExtractionResult

ReportFormat = Literal["json", "pdf"]
_REPORT_ID = re.compile(r"^[0-9a-f]{32}$")

_SECTIONS: list[tuple[str, str, str]] = [
    ("Abstract and overview", "research_analysis", "abstract"),
    ("Research problem", "research_analysis", "research_problem"),
    ("Objectives", "research_analysis", "objectives"),
    ("Motivation", "research_analysis", "motivation"),
    ("Background", "research_analysis", "background"),
    ("Methodology", "research_analysis", "methodology"),
    ("Algorithms and models", "technical_analysis", "algorithms_and_models"),
    ("Dataset and experimental setup", "technical_analysis", "dataset_and_experiments"),
    ("Results and findings", "research_analysis", "results"),
    ("Research contributions", "technical_analysis", "research_contributions"),
    ("Limitations", "research_analysis", "limitations"),
    ("Future scope", "research_analysis", "future_scope"),
    ("Technical methodology breakdown", "technical_analysis", "methodology_breakdown"),
    ("Technical terminology", "technical_analysis", "technical_terminology"),
]

_ORIGIN_LABEL = {
    "directly_extracted": "from the paper",
    "author_claimed": "author's claim",
    "system_inferred": "SYSTEM INFERENCE",
    "system_explanation": "SYSTEM EXPLANATION",
}


def _claims_in(result: ExtractionResult, part: str, name: str):
    prefix = f"{part}.{name}"
    return [
        c for c in result.claims if c.field_path == prefix or c.field_path.startswith(prefix + ".")
    ]


def _page_ref(result: ExtractionResult, claim) -> str:
    records = {e.evidence_id: e for e in result.evidence_registry}
    pages = []
    for evidence_id in claim.evidence_ids:
        record = records.get(evidence_id)
        if record and record.pdf_page_index is not None:
            label = record.displayed_page_number or f"PDF index {record.pdf_page_index}"
            pages.append(f"p. {label}")
    return ", ".join(dict.fromkeys(pages)) or "no located source"


def write_report(
    settings: Settings,
    document_id: str,
    title: str | None,
    result: ExtractionResult,
    fmt: ReportFormat,
) -> str:
    """Write a report file and return its ID."""
    settings.reports_path.mkdir(parents=True, exist_ok=True)
    report_id = uuid.uuid4().hex
    path = settings.reports_path / f"{document_id}_{report_id}.{fmt}"
    if fmt == "json":
        path.write_text(json.dumps(result.model_dump(mode="json"), indent=2), encoding="utf-8")
    else:
        _write_pdf(path, title, result)
    return report_id


def find_report(settings: Settings, report_id: str) -> Path:
    if not _REPORT_ID.match(report_id):
        raise AppError(404, "report_not_found", "Report not found.")
    matches = list(settings.reports_path.glob(f"*_{report_id}.*"))
    if not matches:
        raise AppError(404, "report_not_found", "Report not found.")
    return matches[0]


def _write_pdf(path: Path, title: str | None, result: ExtractionResult) -> None:
    from xml.sax.saxutils import escape

    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    styles = getSampleStyleSheet()
    story: list[Any] = []

    def para(text: str, style: str = "BodyText") -> None:
        story.append(Paragraph(escape(text), styles[style]))

    para(f"Research analysis: {title or 'untitled paper'}", "Title")
    para(
        "Generated by the Agentic Research Assistant. Items are labelled with their origin "
        "and verification status against the paper's own text; 'SYSTEM INFERENCE' and "
        "'SYSTEM EXPLANATION' items are not statements by the authors. Verification is "
        "automatic and can be wrong.",
        "Italic",
    )
    story.append(Spacer(1, 8))

    para("1. Paper metadata", "Heading2")
    for name, value in result.paper_metadata:
        shown = ", ".join(value.value) if isinstance(value.value, list) else value.value
        if name == "abstract":
            continue
        para(
            f"{name.replace('_', ' ').capitalize()}: "
            f"{shown if shown not in (None, '') else 'not found in the paper'}"
        )

    for number, (heading, part, name) in enumerate(_SECTIONS, start=2):
        para(f"{number}. {heading}", "Heading2")
        category = getattr(getattr(result, part), name)
        if name == "abstract" and category.original_abstract.value:
            para(f"Original abstract: {category.original_abstract.value}")
        claims = _claims_in(result, part, name)
        if not claims:
            reason = (
                "could not be processed"
                if category.task_status == "failed"
                else "not found in the paper"
            )
            para(f"Not reported: {reason}.", "Italic")
            continue
        for claim in claims:
            para(
                f"• {claim.claim_text}  [{_ORIGIN_LABEL[claim.origin.value]}; "
                f"{claim.verification_status.value.replace('_', ' ')}; "
                f"{_page_ref(result, claim)}]"
            )

    para(f"{len(_SECTIONS) + 2}. Verification summary", "Heading2")
    for status, count in sorted(result.processing_metadata.verification_summary.items()):
        para(f"{status.replace('_', ' ')}: {count}")

    para(f"{len(_SECTIONS) + 3}. Evidence and page references", "Heading2")
    for record in result.evidence_registry:
        if record.pdf_page_index is None:
            continue
        label = record.displayed_page_number or f"PDF index {record.pdf_page_index}"
        para(
            f"{record.evidence_id} ({record.claim_id}), p. {label}, "
            f"{record.section_name or 'section unknown'}: “{record.source_text}”"
        )

    meta = result.processing_metadata
    para("Provenance", "Heading2")
    para(
        f"Model {meta.model_id}; prompt {meta.prompt_version}; schema {meta.schema_version}; "
        f"embedding {meta.embedding_model_id}; index {meta.index_version}."
    )
    SimpleDocTemplate(str(path), pagesize=A4, title=title or "Research analysis").build(story)
